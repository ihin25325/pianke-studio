"""Generate original synthetic demo media locally; never import a private queue."""
import argparse
import json
from pathlib import Path
import subprocess
import sys
import time
import video_sources
import product_render as renderer

ROOT = Path(__file__).resolve().parents[1]
DEMO_URL = 'https://example.com/pianke-demo.mp4'


def generate():
    folder = ROOT / 'sources/demo'
    folder.mkdir(parents=True, exist_ok=True)
    source = folder / 'source.mp4'
    info = folder / 'source.info.json'
    if source.exists() != info.exists():
        raise ValueError('Demo folder is incomplete; preserve its files and inspect before rerunning.')
    if not source.exists():
        partial = folder / ('demo_' + str(time.time_ns()) + '.mp4')
        command = [str(renderer.FFMPEG), '-v', 'error', '-nostdin', '-n', '-f', 'lavfi',
                   '-i', 'testsrc2=s=640x360:r=30:d=6', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=6',
                   '-c:v', 'libx264', '-threads', '2', '-preset', 'fast', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-shortest', str(partial)]
        result = subprocess.run(command, capture_output=True, timeout=60)
        if result.returncode:
            raise ValueError('Synthetic demo generation failed; run SETUP.bat first.')
        partial.rename(source)
        metadata = {'id': video_sources.source_key(DEMO_URL), '_workbench_source_id': video_sources.source_key(DEMO_URL),
                    '_workbench_source_url': DEMO_URL, 'title': 'Synthetic demo, not a real product',
                    'duration': 6, 'extractor': 'local-synthetic', 'license': 'MIT, generated by this project'}
        info.write_text(json.dumps(metadata, indent=2), encoding='utf-8')
    return source


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--render', action='store_true')
    args = parser.parse_args()
    source = generate()
    print('Demo source ready. Import examples/products.csv into the workbench to try it.')
    if args.render:
        cfg = json.loads((ROOT / 'configs/defaults.json').read_text(encoding='utf-8'))
        cfg.update(source=str(source), output_prefix='demo_' + str(time.time_ns()), max_duration_seconds=6,
                   segments=[{'start': 0, 'end': 6}], source_references={'kind': 'local-synthetic', 'video': DEMO_URL})
        folder = ROOT / 'work/demo'
        folder.mkdir(parents=True, exist_ok=True)
        file = folder / (cfg['output_prefix'] + '.json')
        file.write_text(json.dumps(cfg, ensure_ascii=False), encoding='utf-8')
        return renderer.render(file)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
